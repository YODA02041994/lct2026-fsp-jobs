"""Проверяет понимание SLO, бюджета ошибок, алертов по скорости сгорания, стратегий выката и автошкалирования
в Kubernetes/Prometheus. Утверждения сгруппированы парами «тема: верное / неверное», в один экземпляр тема попадает
один раз, плюс два непарных неверных. Сверено с sre.google/workbook/alerting-on-slos/ и
kubernetes.io/docs/tasks/run-application/horizontal-pod-autoscale/."""
from __future__ import annotations
import random
from ..base import template, Instance, shuffle_options
from ..common import _run_python, _sql_eval, _sql_block, _choice, _multi


@template("gen_devops_lead_slo_alert_rollout", title="SLO, алерты и стратегии выката",
          competency="DevOps: SLO, алерты и выкат релизов",
          specializations=["devops"], technologies=["kubernetes", "prometheus"],
          fmt="multichoice", grade_level="lead", difficulty_shift=0.2)
def _devops_lead_slo_alert_rollout(rng: random.Random) -> Instance:
    svc = rng.choice(["checkout-api", "payments-gateway", "catalog-service", "auth-service", "search-api"])
    ns = rng.choice(["prod", "prod-eu", "prod-us", "prod-core"])
    window = rng.choice(["28 дней", "30 дней", "7 дней", "14 дней"])
    slo = rng.choice(["99.9%", "99.95%", "99.5%", "99.99%"])
    scenario = rng.randrange(4)

    if scenario == 0:
        question = (f"Сервис {svc} в namespace {ns} имеет SLO доступности {slo} на окне {window}. "
                    f"Бюджет ошибок уже израсходован на 80%. Какие решения корректны? Выберите все подходящие.")
        pairs = [
            (f"Замедлить выкат новых версий {svc}, пока бюджет ошибок не восстановится, — это и есть политика бюджета ошибок.",
             "Бюджет ошибок можно не учитывать, если причина недоступности — плановое обслуживание."),
            ("Алерт на сгорание бюджета ошибок строится по симптомам (доля ошибок, задержка — сами SLI), "
             "а не по причинам (CPU, рестарты pod).",
             f"Алерт по росту CPU pod {svc} — это симптомный алерт по SLO."),
            (f"При полном исчерпании бюджета ошибок заморозить рискованные изменения в {svc} до конца окна SLO.",
             "После исчерпания бюджета ошибок нужно повысить целевой SLO, чтобы бюджет появился снова."),
            ("Алерты на скорость сгорания делают по нескольким окнам: быстрое сгорание (например, 1 ч и 5 мин, 14,4×) "
             "вызывает дежурного, медленное (3 дня и 6 ч, 1×) заводит задачу; это отдельные правила Prometheus.",
             "Одного алерта по доле ошибок за последние 5 минут достаточно: он ловит и быстрое, и медленное сгорание бюджета."),
        ]
        extra_wrong = [
            "Бюджет ошибок отсчитывается с момента последнего инцидента, а не по скользящему окну SLO.",
            "Исчерпанный бюджет ошибок обнуляют решением дежурного, чтобы не блокировать релизы.",
        ]
        expl = ("Бюджет ошибок — допустимая доля неуспешных запросов за окно SLO; при его исчерпании замораживают рискованные "
                "изменения. Алерты строят по симптомам (SLI) и по скорости сгорания на нескольких окнах: короткое окно одно "
                "либо шумит, либо пропускает медленное сгорание. Повышение SLO бюджет только уменьшает.")
    elif scenario == 1:
        question = (f"Команда выкатывает новую версию {svc} в {ns}. Нужно снизить риск для пользователей. "
                    f"Какие утверждения о стратегиях выката верны? Выберите все подходящие.")
        pairs = [
            ("Канареечный выкат направляет малую долю трафика на новую версию и постепенно её увеличивает.",
             "Канареечный выкат избавляет от необходимости в SLO — достаточно смотреть логи новой версии."),
            ("Сине-зелёный выкат держит две полные среды и переключает трафик целиком после проверки.",
             "При сине-зелёном выкате обе среды постоянно и одновременно обслуживают продакшн-трафик."),
            ("Для канареечного выката нужны метрики с разбивкой по версии (метка version в Prometheus), иначе сравнить версии нельзя.",
             "Канареечному выкату не нужны метрики по версиям: достаточно общих метрик сервиса."),
            ("Автоматический откат канарейки возможен по порогу доли ошибок или задержки, измеренных на новой версии.",
             "Откат канарейки требует полного повторного выката предыдущей версии во все pod'ы."),
        ]
        extra_wrong = [
            "Сине-зелёный выкат заменяет существующие pod'ы по одному, без второй среды.",
            "Сине-зелёный выкат дешевле канареечного по ресурсам, потому что не требует второй среды.",
        ]
        expl = ("Канареечный выкат — постепенное переключение доли трафика с метриками по версии; сине-зелёный — две "
                "полные среды и переключение целиком. Оба требуют наблюдаемости и допускают автоматический откат "
                "(канарейке достаточно вернуть трафик старой версии); замена pod'ов по одному — это rolling update.")
    elif scenario == 2:
        question = (f"Для {svc} в {ns} настроено автошкалирование HPA по CPU. При росте задержки pod'ы не успевают "
                    f"масштабироваться. Какие меры корректны? Выберите все подходящие.")
        pairs = [
            ("Добавить масштабирование по пользовательской метрике (RPS или длина очереди) через Prometheus Adapter "
             "(API custom.metrics.k8s.io).",
             "HPA по CPU всегда реагирует быстрее, чем по RPS, и потому предпочтителен."),
            ("Задать readiness и startup probes, чтобы новые pod'ы получали трафик только после прогрева, а не отбрасывали запросы.",
             "HPA сам добавляет узлы в кластер, поэтому Cluster Autoscaler не нужен."),
            ("Проверить, что у контейнеров заданы requests по CPU: без них HPA не может вычислить утилизацию и не масштабирует.",
             "Для HPA по утилизации CPU достаточно задать limits: requests не нужны."),
            ("Ускорить рост через behavior.scaleUp (политика «+N pod'ов или +X % за период»), оставив стабилизационное окно "
             "только для scaleDown.",
             "Увеличить stabilizationWindowSeconds для scaleUp — так HPA будет добавлять pod'ы быстрее."),
        ]
        extra_wrong = [
            "HPA опрашивает метрики раз в 5 минут, поэтому быстрее реагировать невозможно.",
            "При масштабировании по пользовательской метрике requests у контейнеров задавать нельзя.",
        ]
        expl = ("HPA по CPU запаздывает относительно нагрузки; метрика RPS/очереди через адаптер и заданные requests дают "
                "корректный расчёт и быструю реакцию, probes защищают от трафика на непрогретые pod'ы. Стабилизационное окно "
                "замедляет масштабирование (для scaleUp по умолчанию 0 с, для scaleDown 300 с), период опроса HPA — 15 с, "
                "узлы добавляет Cluster Autoscaler.")
    else:
        question = (f"После инцидента в {svc} ({ns}) команда разбирает алерты Prometheus. "
                    f"Какие практики разбора инцидента корректны? Выберите все подходящие.")
        pairs = [
            ("Разбор без поиска виноватых: фокус на причинах и улучшении системы.",
             "Алерты по причинам (CPU, память, рестарты) полностью заменяют алерты по симптомам: причина видна раньше."),
            ("Каждый алерт требует действия: у него есть понятный шаг реагирования и владелец.",
             "Если алерт сработал, а пользователи проблем не заметили, его нужно оставить без изменений."),
            ("По итогам инцидента добавляют или уточняют алерты и SLO, если обнаружен пробел в наблюдаемости.",
             "SLO пересматривают только раз в год, независимо от инцидентов."),
            ("Метрики RED (частота запросов, доля ошибок, длительность) — основа симптомных алертов для сервиса.",
             "Метод USE (utilization, saturation, errors) заменяет RED для алертов по пользовательскому опыту сервиса."),
        ]
        extra_wrong = [
            "Постмортем пишут только при нарушении SLO; инциденты без нарушения разбирать не нужно.",
            "Дежурного нужно вызывать на каждое превышение порога за одну минуту, чтобы ничего не пропустить.",
        ]
        expl = ("Разбор без поиска виноватых, алерты с понятным действием и владельцем, обновление SLO и алертов по итогам — "
                "стандартные практики. Симптомные алерты строят по RED (запросы, ошибки, длительность); USE описывает "
                "ресурсы и симптомы для пользователя не заменяет. Шумный алерт перенастраивают, а не оставляют.")

    k = rng.randint(2, 3)
    order = list(range(len(pairs)))
    rng.shuffle(order)
    correct = [pairs[i][0] for i in order[:k]]
    wrong = [pairs[i][1] for i in order[k:]] + list(extra_wrong)
    return _multi(rng, question, correct, wrong, expl)
