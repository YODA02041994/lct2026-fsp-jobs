"""Проверка понимания элементов BPMN и поиска противоречия в постановке процесса."""
from __future__ import annotations
import random
from ..base import template, Instance, shuffle_options
from ..common import _run_python, _sql_eval, _sql_block, _choice, _multi


@template("gen_analytics_bpmn_gateway_reading", title="Чтение схемы BPMN и выбор шлюза",
          competency="BPMN: шлюзы, события, дорожки",
          specializations=["analytics"], technologies=["bpmn", "system_analysis"],
          fmt="choice", grade_level="middle", difficulty_shift=0.1)
def _bpmn_gateway_reading(rng: random.Random) -> Instance:
    sysname = rng.choice(["Оформление заказа", "Обработка заявки", "Приём платежа",
                          "Регистрация клиента", "Выдача кредита", "Отгрузка товара",
                          "Согласование договора"])
    n_branches = rng.randint(2, 4)
    roles = rng.sample(["менеджер", "бухгалтер", "кладовщик", "юрист", "кассир", "оператор"], 2)

    cases = []

    cases.append((
        f"В процессе «{sysname}» после проверки данных стоит исключающий шлюз (XOR) с {n_branches} "
        f"исходящими потоками, условия которых не пересекаются и покрывают все возможные значения признака. "
        f"Что произойдёт при выполнении экземпляра процесса?",
        "Сработает ровно один исходящий поток — тот, чьё условие истинно",
        [
            "Сработает ровно один исходящий поток — тот, чьё условие истинно",
            "Сработают все исходящие потоки, условия которых истинны",
            "Сработает минимум один поток, остальные будут ждать слияния",
            "Процесс остановится с ошибкой, пока не выбран поток по умолчанию",
            "Сработает поток по умолчанию, потому что условия не пересекаются",
            "Создастся по одному экземпляру процесса на каждый исходящий поток",
        ],
        "Исключающий шлюз (XOR) выбирает ровно один исходящий поток — первый, чьё условие истинно; "
        "если ни одно не истинно, используется поток по умолчанию."
    ))

    cases.append((
        f"В процессе «{sysname}» после стартового события стоит параллельный шлюз (AND) с {n_branches} "
        f"исходящими потоками, которые затем сходятся в параллельном шлюзе-слиянии. "
        f"Что верно про поведение такого фрагмента?",
        "Все ветки выполняются параллельно, а слияние ждёт завершения каждой из них",
        [
            "Все ветки выполняются параллельно, а слияние ждёт завершения каждой из них",
            "Выполняется только одна ветка, остальные игнорируются",
            "Ветки выполняются последовательно в порядке их объявления в схеме",
            "Слияние пропускает первую завершившуюся ветку, остальные отменяются",
            "Параллельный шлюз требует ровно двух исходящих потоков, иначе схема некорректна",
            "Слияние срабатывает при поступлении хотя бы одной ветки, остальные ждут",
        ],
        "Параллельный шлюз (AND) активирует все исходящие потоки, а парный шлюз-слияние "
        "синхронизирует их: ждёт завершения каждой ветки перед продолжением."
    ))

    cases.append((
        f"В процессе «{sysname}» после проверки набора признаков стоит включающий шлюз (OR) с {n_branches} "
        f"исходящими потоками. Условия нескольких потоков оказались истинными одновременно. "
        f"Что произойдёт?",
        "Будут активированы все потоки, чьи условия истинны",
        [
            "Будут активированы все потоки, чьи условия истинны",
            "Будет активирован только первый поток с истинным условием",
            "Возникнет ошибка: включающий шлюз допускает только одно истинное условие",
            "Будет активирован поток по умолчанию вместо истинных",
            "Будет активирован ровно один поток, выбранный случайно",
            "Все потоки будут активированы, даже с ложными условиями",
        ],
        "Включающий шлюз (OR) активирует все исходящие потоки, чьи условия истинны — "
        "от одного до всех, в отличие от исключающего шлюза."
    ))

    cases.append((
        f"В процессе «{sysname}» на границе пользовательской задачи «Согласование» прикреплено "
        f"промежуточное событие-таймер с прерывающим типом. Что произойдёт, если таймер сработает "
        f"до завершения задачи?",
        "Задача будет прервана, и процесс пойдёт по потоку от события-таймера",
        [
            "Задача будет прервана, и процесс пойдёт по потоку от события-таймера",
            "Задача продолжит выполняться, а таймер запустит параллельную ветку",
            "Таймер будет проигнорирован, пока задача не завершится",
            "Процесс завершится с ошибкой таймаута",
            "Создастся новая задача-дубликат, исходная останется активной",
            "Событие-таймер на границе задачи допустимо только для подпроцессов",
        ],
        "Прерывающее граничное событие отменяет активную задачу и передаёт управление "
        "по исходящему потоку события; непрерывающее — оставило бы задачу активной."
    ))

    cases.append((
        f"В процессе «{sysname}» две дорожки: «{roles[0]}» и «{roles[1]}». Задача «Проверить документы» "
        f"лежит на дорожке «{roles[0]}», а следующая за ней задача «Подписать» — на дорожке «{roles[1]}». "
        f"Что это означает для исполнителей?",
        "Задачи выполняют разные роли: сначала один исполнитель, затем другой",
        [
            "Задачи выполняют разные роли: сначала один исполнитель, затем другой",
            "Обе задачи выполняет одна и та же роль, дорожки здесь декоративны",
            "Дорожки задают порядок выполнения, но не исполнителей",
            "Между дорожками нужен поток сообщений, а не поток управления",
            "Задача «Подписать» начнётся одновременно с «Проверить документы»",
            "Переход между дорожками требует параллельного шлюза",
        ],
        "Дорожки (lanes) внутри одного пула закрепляют задачи за ролями или подразделениями; переход между "
        "дорожками означает смену исполнителя. Поток управления (sequence flow) свободно идёт между дорожками, "
        "а поток сообщений нужен только между разными пулами."
    ))

    cases.append((
        f"В постановке процесса «{sysname}» сказано: «После проверки заявка либо одобряется, либо "
        f"отклоняется, либо отправляется на доработку» — ровно один исход. Аналитик поставил после проверки "
        f"параллельный шлюз (AND) с тремя исходящими потоками. В чём ошибка?",
        "Нужен исключающий шлюз (XOR): исходы взаимоисключающие, а параллельный шлюз запустит все три потока",
        [
            "Нужен исключающий шлюз (XOR): исходы взаимоисключающие, а параллельный шлюз запустит все три потока",
            "Ошибки нет: параллельный шлюз допускает любое число исходящих потоков",
            "Нужен включающий шлюз (OR), потому что ветвей больше двух",
            "Достаточно дописать условия на исходящих потоках параллельного шлюза",
            "Нужно добавить к параллельному шлюзу поток по умолчанию",
            "Ошибка в том, что у любого шлюза может быть не больше двух исходящих потоков",
        ],
        "Параллельный шлюз активирует все исходящие потоки и условий на них не вычисляет, поэтому заявка пошла бы "
        "по трём путям сразу. Выбор ровно одного исхода по условию моделирует исключающий шлюз (при необходимости "
        "с потоком по умолчанию)."
    ))

    cases.append((
        f"В процессе «{sysname}» внутри подпроцесса на границе прикреплено событие-ошибка (прерывающее). "
        f"Что произойдёт при возникновении ошибки в подпроцессе?",
        "Подпроцесс прервётся, и управление перейдёт по потоку от события-ошибки наружу",
        [
            "Подпроцесс прервётся, и управление перейдёт по потоку от события-ошибки наружу",
            "Ошибка будет проигнорирована, подпроцесс продолжит работу",
            "Подпроцесс завершится успешно, а ошибка попадёт в лог",
            "Будет запущен компенсирующий подпроцесс для всех активных задач",
            "Ошибка вызовет остановку всего пула процессов без обработки",
            "Событие-ошибка допустимо только на уровне всего процесса, не подпроцесса",
        ],
        "Прерывающее граничное событие-ошибка отменяет активность подпроцесса и передаёт "
        "управление по исходящему потоку этого события."
    ))

    idx = rng.randrange(len(cases))
    question, correct_text, options, expl = cases[idx]
    correct = options.index(correct_text)
    return _choice(rng, question, options, correct, expl)
