"""Жизненный цикл модели в проде: дрейф данных, утечка признаков, разбиение по времени, мониторинг, A/B.

Опора: scikit-learn, common_pitfalls (data leakage: fit только на обучающих данных, иначе оценка завышена) и
cross_validation (случайное разбиение для временных данных нарушает независимость наблюдений — TimeSeriesSplit).
Метрики в пуле — те, где падение означает ухудшение (logloss намеренно исключён)."""
from __future__ import annotations
import random
from ..base import template, Instance, shuffle_options
from ..common import _run_python, _sql_eval, _sql_block, _choice, _multi


@template("gen_data_model_in_prod_lifecycle", title="Модель в проде: дрейф, утечка, мониторинг, A/B",
          competency="ML в проде: жизненный цикл модели",
          specializations=["data"], technologies=["ml", "system_design"],
          fmt="multichoice", grade_level="lead", difficulty_shift=0.0)
def _model_in_prod(rng: random.Random) -> Instance:
    model = rng.choice(["fraud-v3", "churn-xgb", "ltv-lgbm", "recs-two-tower", "risk-catboost"])
    feat = rng.choice(["tx_amount", "session_len", "days_since_signup", "user_tenure", "order_total"])
    days = rng.choice([14, 21, 30, 45, 60])
    share = rng.choice([10, 15, 20, 25, 30])
    drift = rng.choice(["PSI", "расстояние Кульбака — Лейблера", "тест Колмогорова — Смирнова", "расстояние Вассерштейна"])
    metric = rng.choice(["ROC-AUC", "PR-AUC", "F1", "precision@k"])

    true_pool = [
        f"Если распределение признака {feat} сместилось (сдвиг среднего или квантилей), метрика {metric} модели {model} "
        "может падать без изменений в коде — это дрейф данных.",
        f"Утечка признаков: если {feat} вычисляется по данным, появившимся после момента предсказания, оценка на отложенной "
        "выборке завышена, а в проде качество резко падает.",
        "Случайное разбиение по строкам при временных данных даёт утечку будущего: правильнее разбивать по времени "
        "(обучение до даты T, проверка после).",
        "Для мониторинга в проде нужно логировать входные признаки и предсказания, чтобы сравнивать живое распределение "
        f"с обучающим ({drift}).",
        f"При выпуске новой версии {model} через A/B нужен контрольный трафик и метрика качества на нём; решение о выпуске "
        "на весь трафик — по статистически значимому эффекту.",
        f"Если растёт доля значений {feat} вне диапазона обучающей выборки (например, {share} %), модель работает вне области обучения "
        "и качество падает — это тоже дрейф данных.",
    ]
    false_pool = [
        f"Если код модели {model} не менялся, метрика {metric} в проде измениться не может.",
        "Утечка признаков устраняется увеличением скорости обучения (learning rate) и числа эпох.",
        "Случайное разбиение по строкам всегда корректно для временных рядов — порядок наблюдений не важен.",
        f"Мониторить в проде достаточно метрику {metric} на разметке; логировать признаки не нужно.",
        "При A/B-выпуске модели контрольный трафик не нужен: достаточно сравнить метрику до и после релиза.",
        f"Сдвиг распределения {feat} на {share} % не влияет на предсказания, если при обучении признаки были нормированы.",
    ]
    k = rng.randint(2, 3)
    correct = rng.sample(true_pool, k)
    wrong = rng.sample(false_pool, 6 - k)
    q = (f"Команда выпустила модель {model} в прод и через {days} дней видит падение {metric}. "
         "Какие утверждения о жизненном цикле модели в проде верны? Выберите все подходящие.")
    expl = ("Падение качества без изменений кода объясняется дрейфом данных или утечкой признаков при обучении "
            "(оценка на отложенной выборке была завышена). Разбиение по времени, логирование входов и предсказаний "
            "и контрольная группа при A/B — обязательные практики; нормировка признаков сдвиг распределения не устраняет.")
    return _multi(rng, q, correct, wrong, expl)
