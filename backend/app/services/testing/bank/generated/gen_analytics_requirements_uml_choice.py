"""Проверяет понимание типов артефактов требований (функциональное, нефункциональное, пользовательская история,
критерий приёмки) и выбора подходящей диаграммы UML под задачу. Дистракторы берутся в основном из того же семейства."""
from __future__ import annotations
import random
from ..base import template, Instance, shuffle_options
from ..common import _run_python, _sql_eval, _sql_block, _choice, _multi

# роль: (именительный, родительный, дательный, творительный)
_ROLES = {
    "клиент": ("клиента", "клиенту", "клиентом"),
    "менеджер": ("менеджера", "менеджеру", "менеджером"),
    "курьер": ("курьера", "курьеру", "курьером"),
    "администратор": ("администратора", "администратору", "администратором"),
    "студент": ("студента", "студенту", "студентом"),
    "тренер": ("тренера", "тренеру", "тренером"),
    "библиотекарь": ("библиотекаря", "библиотекарю", "библиотекарем"),
}
_REQ = ["Функциональное требование", "Нефункциональное требование", "Пользовательская история", "Критерий приёмки"]
_DIAG = [
    "Диаграмма деятельности (activity)",
    "Диаграмма классов (class)",
    "Диаграмма последовательности (sequence)",
    "Диаграмма состояний (state machine)",
    "Диаграмма вариантов использования (use case)",
    "Диаграмма развёртывания (deployment)",
    "Диаграмма компонентов (component)",
]


@template("gen_analytics_requirements_uml_choice", title="Требования и выбор UML-диаграммы",
          competency="Системный анализ: требования и UML",
          specializations=["analytics"], technologies=["system_analysis", "uml"],
          fmt="choice", grade_level="junior", difficulty_shift=-0.2)
def _analytics_requirements_uml(rng: random.Random) -> Instance:
    sys_name = rng.choice(["КлиентБанк", "ОнлайнЗапись", "СкладСервис", "УчебныйПортал",
                           "ДоставкаЕда", "ФитнесТрекер", "БиблиотекаКниг"])
    nom = rng.choice(list(_ROLES))
    gen, dat, ins = _ROLES[nom]
    action = rng.choice(["оформить заказ", "отменить бронь", "оплатить счёт", "загрузить файл",
                         "отследить доставку", "записаться на занятие", "вернуть книгу"])
    n_sec = rng.randint(2, 8)
    n_users = rng.choice([500, 1000, 2000, 5000, 10000, 20000, 50000])

    cases = [
        (f"Система «{sys_name}»: {nom} должен иметь возможность {action}.",
         "Функциональное требование",
         "Описано поведение системы — что она должна позволять делать пользователю, значит требование функциональное."),
        (f"Система «{sys_name}» должна отвечать на запрос {gen} не дольше {n_sec} с при {n_users} одновременных пользователях.",
         "Нефункциональное требование",
         "Задано ограничение на время отклика и нагрузку — характеристика качества, то есть нефункциональное требование."),
        (f"Как {nom}, я хочу {action}, чтобы не тратить время на звонок в поддержку.",
         "Пользовательская история",
         "Формулировка «Как <роль>, я хочу <действие>, чтобы <польза>» — шаблон пользовательской истории."),
        (f"Дано: {nom} авторизован. Когда {nom} нажимает «{action}». Тогда система показывает подтверждение.",
         "Критерий приёмки",
         "Структура «Дано — Когда — Тогда» (Given — When — Then) описывает проверяемое условие приёмки истории."),
        (f"Нужно показать, как {nom} выполняет сценарий «{action}» по шагам: от входа до подтверждения, с точками принятия решений.",
         "Диаграмма деятельности (activity)",
         "Пошаговый сценарий с ветвлениями и решениями изображает диаграмма деятельности."),
        (f"Нужно показать, какие сущности есть в «{sys_name}» и как они связаны между собой по структуре: атрибуты, связи, кратности.",
         "Диаграмма классов (class)",
         "Статическая структура сущностей, их атрибутов и связей — это диаграмма классов."),
        (f"Нужно показать обмен сообщениями между {ins} и сервисом во времени в сценарии «{action}».",
         "Диаграмма последовательности (sequence)",
         "Обмен сообщениями между участниками во времени изображает диаграмма последовательности."),
        (f"Нужно показать, какие состояния проходит заказ в сценарии «{action}» и по каким событиям состояние меняется.",
         "Диаграмма состояний (state machine)",
         "Жизненный цикл объекта с состояниями и переходами — это диаграмма состояний."),
        (f"Нужно показать, какие варианты использования системы «{sys_name}» доступны {dat}.",
         "Диаграмма вариантов использования (use case)",
         "Набор действий, доступных действующему лицу, показывает диаграмма вариантов использования."),
        (f"Нужно показать, на каких серверах и узлах размещаются части системы «{sys_name}» и как узлы соединены.",
         "Диаграмма развёртывания (deployment)",
         "Размещение артефактов по узлам и связи между узлами — это диаграмма развёртывания."),
    ]

    idx = rng.randrange(len(cases))
    text, correct, expl = cases[idx]

    if correct in _REQ:
        wrong = [p for p in _REQ if p != correct] + rng.sample(_DIAG, 2)
    else:
        wrong = rng.sample([p for p in _DIAG if p != correct], 4) + [rng.choice(_REQ)]
    options = [correct] + wrong

    return _choice(rng, f"{text} Что это за артефакт или какая UML-диаграмма подходит?",
                   options, 0, expl)
