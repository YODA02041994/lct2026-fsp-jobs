"""Идемпотентность и повторная загрузка за прошлые даты в конвейерах Airflow и Spark.

Факты, на которые опираются ключи: Airflow — дата интервала берётся из контекста запуска (data_interval_start /
logical_date; execution_date в Airflow 3 удалён), backfill = повторный запуск за диапазон прошлых интервалов;
Spark — mode('append') дописывает строки, а overwrite партиционированной таблицы источника данных при
spark.sql.sources.partitionOverwriteMode=static удаляет все партиции, подходящие под спецификацию (без указанных
значений — всю таблицу), при dynamic — только партиции, присутствующие в записываемых данных (SPARK-20236)."""
from __future__ import annotations
import random
from ..base import template, Instance, shuffle_options
from ..common import _run_python, _sql_eval, _sql_block, _choice, _multi


@template("gen_data_lead_pipeline_replay", title="Повторная загрузка данных за прошлое",
          competency="Конвейеры данных: идемпотентность, повторная загрузка, партиционирование",
          specializations=["data"], technologies=["airflow", "spark"], fmt="choice",
          grade_level="lead", difficulty_shift=0.2)
def _pipeline_replay(rng: random.Random) -> Instance:
    table = rng.choice(["events", "orders", "pageviews", "transactions", "clicks"])
    dt_col = rng.choice(["event_date", "order_date", "dt", "created_at"])
    dag = rng.choice(["daily_etl", "raw_to_dwh", "events_load", "orders_sync"])
    days = rng.randint(2, 5)
    dn = f"{days} дня" if days < 5 else f"{days} дней"                    # склонение
    cases = [
        (
            f"Ежедневный DAG {dag} пишет в партиционированную по {dt_col} таблицу {table} через INSERT OVERWRITE PARTITION, "
            f"но дату партиции задача вычисляет как «вчера» от текущего времени (date.today() − 1 день). Данные за {dn} "
            "на прошлой неделе загружены с ошибкой, их нужно перезапустить.",
            "Брать дату партиции из контекста запуска (data_interval_start / logical_date), а не из текущего времени, "
            "и после этого перезапустить нужные даты: иначе догрузка за прошлое (backfill) каждый раз перезапишет партицию за вчера.",
            "Перезапись партиции идемпотентна, только если дата партиции привязана к интервалу запуска. При date.today() "
            "любой повторный запуск за прошлое пишет в одну и ту же свежую партицию и портит её.",
        ),
        (
            f"Задача {dag} загружает {table} через INSERT INTO в таблицу без партиционирования. "
            f"DAG упал, и его перезапускают за {dn} с той же логикой.",
            "Повторный запуск INSERT INTO создаст дубликаты: перейти на INSERT OVERWRITE PARTITION по дате "
            "либо удалять строки за целевую дату перед вставкой.",
            "INSERT INTO только добавляет строки, поэтому повторная загрузка за ту же дату удваивает данные. "
            "Идемпотентность достигается заменой партиции или предварительным DELETE за дату.",
        ),
        (
            f"DAG {dag} загружает {table} инкрементально: берёт из источника строки с {dt_col} больше максимальной даты "
            f"в целевой таблице. Выяснилось, что данные за {dn} пришли в источник с опозданием и были пропущены.",
            f"Перейти на выборку по явному интервалу запуска (data_interval_start / data_interval_end) и перезаписывать "
            f"партиции {dt_col} через INSERT OVERWRITE PARTITION за нужные {dn}.",
            "Инкремент по MAX(dt) не увидит опоздавшие данные: они старше максимума. Явный интервал запуска и перезапись "
            "партиции позволяют догрузить пропущенные дни без дублей.",
        ),
        (
            f"Airflow-задача {dag} пишет в {table} через Spark DataFrameWriter с mode('append') без партиционирования. "
            f"После сбоя её перезапускают за {dn}.",
            f"Заменить append на перезапись партиций: partitionBy('{dt_col}') + mode('overwrite') при "
            "spark.sql.sources.partitionOverwriteMode=dynamic, либо удалять строки за целевую дату перед записью.",
            "append при повторном запуске дублирует данные. Динамическая перезапись партиций заменяет только партиции "
            "за загружаемые даты и делает запись идемпотентной.",
        ),
        (
            f"В DAG {dag} задача сначала удаляет партицию {dt_col} за дату запуска, затем вставляет данные заново "
            f"(delete + insert). Нужно перезапустить {dn} после сбоя источника.",
            "Перезапуск безопасен: delete + insert по партиции идемпотентен, повторный запуск удалит и вставит те же данные за дату.",
            "Удаление партиции за дату и вставка заново приводят таблицу к одному и тому же состоянию при любом числе "
            "повторов — менять логику не нужно, достаточно перезапустить нужные даты.",
        ),
        (
            f"DAG {dag} пишет в parquet-таблицу {table} через df.write.mode('overwrite').partitionBy('{dt_col}') "
            f"при настройках Spark по умолчанию (partitionOverwriteMode = static). Нужно догрузить {dn}.",
            "Включить spark.sql.sources.partitionOverwriteMode=dynamic (или option('partitionOverwriteMode', 'dynamic')): "
            "в статическом режиме overwrite без указанных значений партиции удалит все партиции таблицы, "
            "в динамическом — только те, что есть в записываемых данных.",
            "В статическом режиме Spark перед записью удаляет все партиции, подходящие под спецификацию; без указанных "
            "значений это вся таблица. Динамический режим перезаписывает только партиции, присутствующие в новом DataFrame.",
        ),
        (
            f"Стоит SLA: данные за день должны быть готовы к 07:00. DAG {dag} пишет в {table} через INSERT OVERWRITE PARTITION "
            f"по {dt_col}; за {dn} он упал ночью, нужно восстановить эти дни и не сорвать следующий SLA.",
            f"Запустить догрузку (backfill) за {dn} параллельно с текущим запуском: запись идёт через "
            "INSERT OVERWRITE PARTITION по дате, поэтому запуски пишут в разные партиции и не мешают друг другу.",
            "Перезапись партиций изолирует запись по датам: догрузка прошлых дней и текущий запуск не конфликтуют "
            "и не создают дублей, а SLA по свежему дню не страдает.",
        ),
    ]
    idx = rng.randrange(len(cases))
    scenario, correct, expl = cases[idx]
    wrong_pool = [
        "Перезапустить DAG за нужные даты с прежней логикой INSERT INTO: Airflow сам не допустит повторной загрузки одного интервала.",
        "Удалить всю таблицу и загрузить всю историю заново с нуля.",
        "Изменить расписание DAG, чтобы следующие запуски шли чаще и «догнали» пропущенные дни.",
        "Поднять retries у задачи до 10: повторные попытки сами доведут данные до корректного состояния.",
        "Добавить DISTINCT в отчётные запросы поверх таблицы, чтобы дубли не были видны.",
        "Перезапустить DAG только за последний день: остальные дни подтянутся автоматически из источника.",
        "Хранить флаг «дата загружена» в отдельной таблице и пропускать повторные запуски за уже загруженные даты.",
    ]
    options = [correct] + rng.sample(wrong_pool, 5)
    return _choice(rng, scenario + " Какое решение корректно и обеспечивает идемпотентность?", options, 0, expl)
